CREATE TABLE IF NOT EXISTS pengguna (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(100) NOT NULL,
    username VARCHAR(50) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'MEMBER'
        CHECK (role IN ('SUPER_ADMIN', 'ADMIN', 'MEMBER')),
    alamat VARCHAR(255),
    no_telepon VARCHAR(30)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_pengguna_username_lower
    ON pengguna (LOWER(username));

CREATE TABLE IF NOT EXISTS buku (
    id_buku VARCHAR(50) PRIMARY KEY,
    judul_buku VARCHAR(200) NOT NULL,
    isbn VARCHAR(30) DEFAULT '-',
    pengarang VARCHAR(100) DEFAULT '-',
    penerbit VARCHAR(100) DEFAULT '-',
    tahun_terbit INTEGER DEFAULT 2024,
    stok_buku INTEGER NOT NULL DEFAULT 0 CHECK (stok_buku >= 0)
);

CREATE TABLE IF NOT EXISTS peminjaman (
    id_peminjaman INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_anggota INTEGER NOT NULL REFERENCES pengguna(id),
    id_buku VARCHAR(50) NOT NULL REFERENCES buku(id_buku),
    tanggal_booking DATE NOT NULL,
    tanggal_pinjam DATE,
    tanggal_jatuh_tempo DATE,
    tanggal_kembali_sebenarnya DATE,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('REQUESTED', 'DIPINJAM', 'DIKEMBALIKAN')),
    denda DECIMAL(12, 2) NOT NULL DEFAULT 0 CHECK (denda >= 0)
);

CREATE TABLE IF NOT EXISTS aturan_perpustakaan (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    denda_per_hari INTEGER NOT NULL DEFAULT 2000 CHECK (denda_per_hari >= 0),
    durasi_pinjam_hari INTEGER NOT NULL DEFAULT 7 CHECK (durasi_pinjam_hari >= 1)
);

ALTER TABLE pengguna ENABLE ROW LEVEL SECURITY;
ALTER TABLE buku ENABLE ROW LEVEL SECURITY;
ALTER TABLE peminjaman ENABLE ROW LEVEL SECURITY;
ALTER TABLE aturan_perpustakaan ENABLE ROW LEVEL SECURITY;

